def _price(s: dict) -> str:
    p = s.get("price", "?")
    return f"€{float(p):.2f}" if p != "?" else "?"


def _domains(s: dict) -> str:
    return " ".join(s["rapl_domains"]) or "—"


def _kepler_text(s: dict) -> str:
    k = s["kepler"]
    icon = KEPLER_ICON.get(k, "?")
    label = {"yes": "Recommended", "cond": "Conditional",
             "no": "Not usable", "unknown": "Unknown"}.get(k, k)
    return f"{icon} {label}"


