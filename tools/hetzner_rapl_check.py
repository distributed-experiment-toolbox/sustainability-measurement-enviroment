SORT_KEYS = {
    "price":  lambda s: float(s.get("price", 9999)),
    "ram":    lambda s: int(s.get("ram", 0)),
    "cpu":    lambda s: s.get("cpu", "").lower(),
    "rapl":   lambda s: ["Full","Partial","None","Unknown"].index(
                             s.get("rapl_level","Unknown")),
    "kepler": lambda s: ["yes","cond","unknown","no"].index(
                             s.get("kepler","unknown")),
}


def main() -> None:
    args = build_parser().parse_args()

    # Load data
    if args.file:
        raw = load_file(args.file)
    else:
        raw = fetch_auction(verbose=args.verbose)

    # Enrich
    servers = [enrich(s) for s in raw]

    # Filter
    servers = apply_filters(servers, args)

    # Sort
    key_fn = SORT_KEYS.get(args.sort, SORT_KEYS["price"])
    servers.sort(key=key_fn, reverse=args.desc)

    # Output
    if args.json:
        print_json(servers)
    elif args.csv:
        print_csv(servers)
    else:
        if RICH:
            print_rich(servers)
        else:
            print_plain(servers)
        if not args.no_summary:
            print_summary(servers)


if __name__ == "__main__":
    main()