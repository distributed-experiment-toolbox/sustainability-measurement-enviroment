TIMEOUT = 15


# ─────────────────────────────────────────────────────────────────────────────
# Fetch live auction data
# ─────────────────────────────────────────────────────────────────────────────
def fetch_auction(verbose: bool = False) -> list[dict]:
    """Try each known API URL and return the server list."""
    for url in API_URLS:
        try:
            if verbose:
                print(f"[fetch] trying {url}", file=sys.stderr)
            r = requests.get(url, headers=HEADERS, timeout=TIMEOUT)
            r.raise_for_status()
            data = r.json()
            servers = data.get("server", [])
            if servers:
                if verbose:
                    print(f"[fetch] got {len(servers)} listings from {url}",
                          file=sys.stderr)
                return servers
        except Exception as e:
            if verbose:
                print(f"[fetch] {url} failed: {e}", file=sys.stderr)
            continue

    # Nothing worked – tell the user how to supply their own data
    sys.exit(
        "Could not reach any known Hetzner auction API endpoint.\n"
        "Tip: download the JSON manually and pass it via --file:\n"
        "  curl 'https://www.hetzner.com/_resources/app/jsondata/live_data_sb.json'"
        " > live.json\n"
        "  python hetzner_rapl_check.py --file live.json"
    )


def load_file(path: str) -> list[dict]:
    """Load auction data from a local JSON file."""
    try:
        with open(path) as f:
            data = json.load(f)
        return data.get("server", data) if isinstance(data, dict) else data
    except Exception as e:
        sys.exit(f"Could not read {path}: {e}")


# ─────────────────────────────────────────────────────────────────────────────
# RAPL lookup
# ─────────────────────────────────────────────────────────────────────────────
def lookup(cpu_str: str) -> Optional[RaplProfile]:
    """Return the first matching RaplProfile for a CPU string, or None."""
    low = cpu_str.lower()
    for fragment, profile in RAPL_DB:
        if fragment in low:
            return profile
    return None


# ─────────────────────────────────────────────────────────────────────────────
# Enrich a raw server dict with RAPL data
# ─────────────────────────────────────────────────────────────────────────────
def enrich(server: dict) -> dict:
    cpu = server.get("cpu", "Unknown")
    profile = lookup(cpu)
    if profile:
        return {
            **server,
            "rapl_level":   profile.level,
            "rapl_domains": profile.domains,
            "kepler":       profile.kepler,
            "kernel_min":   profile.kernel_min,
            "vendor":       profile.vendor,
            "arch":         profile.arch,
            "rapl_notes":   profile.notes,
        }
    return {
        **server,
        "rapl_level":   "Unknown",
        "rapl_domains": [],
        "kepler":       "unknown",
        "kernel_min":   "—",
        "vendor":       "Unknown",
        "arch":         "Unknown",
        "rapl_notes":   "CPU not in compatibility database – check manually.",
    }


# ─────────────────────────────────────────────────────────────────────────────
# Filters
# ─────────────────────────────────────────────────────────────────────────────
def apply_filters(servers: list[dict], args) -> list[dict]:
    out = servers
    if args.rapl:
        out = [s for s in out if s["rapl_level"].lower() == args.rapl.lower()]
    if args.kepler:
        out = [s for s in out if s["kepler"].lower() == args.kepler.lower()]
    if args.vendor:
        out = [s for s in out if s["vendor"].lower() == args.vendor.lower()]
    if args.max_price is not None:
        out = [s for s in out
               if float(s.get("price", 9999)) <= args.max_price]
    if args.min_ram is not None:
        out = [s for s in out if int(s.get("ram", 0)) >= args.min_ram]
    if args.ecc:
        out = [s for s in out if s.get("is_ecc", False)]
    if args.nvme:
        out = [s for s in out
               if "nvme" in s.get("freetext", "").lower()
               or s.get("is_highio", False)]
    if args.dc:
        out = [s for s in out
               if any(args.dc.upper() in dc for dc in s.get("datacenter", []))]
    return out


